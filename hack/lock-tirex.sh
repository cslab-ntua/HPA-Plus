#!/usr/bin/env bash
# Hash-lock algorithms/requirements-tirex.in without resolving dependencies: the TiRex target installs
# exactly these pins with --no-deps, so each pin gets the hash of its Linux amd64 Python 3.14 wheel.
set -euo pipefail
cd "$(dirname "$0")/.."
python -c 'import sys; assert sys.version_info[:2] == (3, 14), "use Python 3.14"'
wheels=$(mktemp -d)
trap 'rm -rf "$wheels"' EXIT
python -m pip download --quiet --no-deps --only-binary=:all: --dest "$wheels" \
  --extra-index-url https://download.pytorch.org/whl/cpu -r algorithms/requirements-tirex.in
python - "$wheels" <<'PY'
import hashlib, pathlib, re, sys
wheels = list(pathlib.Path(sys.argv[1]).glob("*.whl"))
norm = lambda s: re.sub(r"[-_.]+", "_", s).lower()
out = ["#", "# This file is autogenerated by bash hack/lock-tirex.sh from requirements-tirex.in.",
       "# Install with --no-deps --require-hashes.", "#", "--extra-index-url https://download.pytorch.org/whl/cpu", ""]
for line in pathlib.Path("algorithms/requirements-tirex.in").read_text().splitlines():
    if not re.match(r"^[A-Za-z0-9]", line):
        continue
    name, version = line.split("==")
    match = [w for w in wheels if norm(w.name.split("-")[0]) == norm(name) and w.name.split("-")[1] == version]
    if len(match) != 1:
        sys.exit("no single wheel for " + line)
    digest = hashlib.sha256(match[0].read_bytes()).hexdigest()
    out += [f"{line} \\", f"    --hash=sha256:{digest}"]
pathlib.Path("algorithms/requirements-tirex.txt").write_text("\n".join(out) + "\n")
print(len(out) // 2 - 3, "pins locked")
PY
